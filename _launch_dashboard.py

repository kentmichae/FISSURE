#!/usr/bin/env python3
"""Launch FISSURE Dashboard with proper DISPLAY and QT_API."""
import os
os.environ["DISPLAY"] = ":99"
os.environ["QT_API"] = "pyqt6"
import sys
sys.path.insert(0, "/home/nebulaone/spark-dev-workspace/FISSURE")
os.chdir("/home/nebulaone/spark-dev-workspace/FISSURE")
import subprocess
result = subprocess.run(
    [sys.executable, "-m", "fissure.Dashboard"],
    env={**os.environ, "DISPLAY": ":99", "QT_API": "pyqt6"},
    cwd="/home/nebulaone/spark-dev-workspace/FISSURE",
)
sys.exit(result.returncode)